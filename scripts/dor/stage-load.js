// Stages DOR NAL/SDF CSVs into staging.nal_<year> / staging.sdf_<year>. Touches ONLY the staging schema.
//   node scripts/dor/stage-load.js --year 2026 --kind sdf|nal [--ddl-only] [--max-growth-gb 14] [--counties 11,12]
// Needs: data/dor/<year>/x_<kind>/<co>_<County>_<KIND>_<year><F|P>/*.csv, scan_<kind>.json (scan-columns.js),
//        docs/quickref.json (xlsx-dump.js of the DOR Quick Reference workbook).
// Types come from the DOR layout (numeric vs alpha, max length) but fall back to text when the data
// contradicts it; code-like fields (*_UC, *_CD, ZIPs, strata) stay text to preserve leading zeros.
// Extra columns: roll_stage (F|P), source_file, match_key (strict alphanumeric PARCEL_ID).
const fs = require('fs'), path = require('path'), csv = require('csv-parser');
const { Client } = require('pg'); const { from: copyFrom } = require('pg-copy-streams');
const { pipeline } = require('stream/promises'); const { Readable } = require('stream');
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i < 0 ? d : (process.argv[i + 1] ?? true); };
const year = arg('year', '2026'), kind = arg('kind'), ddlOnly = process.argv.includes('--ddl-only');
const MAXG = Number(arg('max-growth-gb', 14)) * 1024 ** 3;
const only = arg('counties', null) ? String(arg('counties')).split(',').map(Number) : null;
const root = path.join(__dirname, '..', '..'), base = path.join(root, 'data', 'dor', year);
const scan = JSON.parse(fs.readFileSync(path.join(base, `scan_${kind}.json`), 'utf8'));
const qr = JSON.parse(fs.readFileSync(path.join(base, 'docs', 'quickref.json'), 'utf8'))[kind === 'nal' ? 'NAL Fields' : 'SDF Fields'];
const spec = {};
for (const r of qr.slice(1)) if (r[2]) spec[r[2].trim()] = { len: parseInt(r[5], 10), num: r[6] === 'X' };
const CODEISH = /(_UC|_CD\d?|ZIPCD|_STRT|GRP_NO|CONST_CLASS|_FG)$/;

function pgType(c) {
  const s = scan.cols[c], sp = spec[c];
  if (CODEISH.test(c) || (sp && !sp.num) || s.other > 0 || s.dec > 0) return 'text';
  if (/^EXMPT_\d+$/.test(c)) return s.other > 0 ? 'text' : 'bigint';
  if (s.n === 0) return 'text';                       // never populated this year: keep permissive
  if (c === 'CO_NO') return 'smallint';
  const len = sp && sp.len;
  if (len && len <= 4 && s.maxint < 32000) return 'smallint';
  if (len && len <= 9 && s.maxint < 2e9) return 'integer';
  return 'bigint';
}
const cols = scan.order.map((c) => ({ csv: c, name: c.toLowerCase(), type: pgType(c) }));
const table = `staging.${kind}_${year}`;
const ddl = `-- Generated by scripts/dor/stage-load.js (--year ${year} --kind ${kind}). Staging only; never touches public.*
CREATE SCHEMA IF NOT EXISTS staging;
CREATE TABLE IF NOT EXISTS ${table} (
${cols.map((c) => `  ${c.name} ${c.type}`).join(',\n')},
  roll_stage char(1) NOT NULL,   -- F = final, P = preliminary
  source_file text NOT NULL,
  match_key text                 -- strict alphanumeric PARCEL_ID; joins to parcels_v2.match_key
);
`;
const idx = `CREATE INDEX IF NOT EXISTS ${kind}_${year}_match_key_idx ON ${table} (match_key, co_no);
CREATE INDEX IF NOT EXISTS ${kind}_${year}_co_no_idx ON ${table} (co_no);
`;
fs.writeFileSync(path.join(root, 'db', 'migrations', `007_staging_${kind}_${year}.sql`), ddl + idx);
if (ddlOnly) {
  console.log(cols.reduce((a, x) => { a[x.type] = (a[x.type] || 0) + 1; return a; }, {}));
  process.exit(0);
}

const env = fs.readFileSync(path.join(root, '.env.local'), 'utf8');
const url = env.match(/^DATABASE_URL=(.*)$/m)[1].trim().replace(/^["']|["']$/g, '').replace(/[?&]sslmode=[^&]*/, '');
const gb = (b) => (b / 1024 ** 3).toFixed(2) + ' GB';
const q = (v) => (v === '' ? '' : '"' + v.replace(/"/g, '""') + '"');
const strict = (v) => { const k = String(v == null ? '' : v).toUpperCase().replace(/[^A-Z0-9]/g, ''); return k || null; };

(async () => {
  const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false }, keepAlive: true });
  await c.connect(); await c.query('SET statement_timeout = 0');
  const baseline = Number((await c.query('select pg_database_size(current_database()) s')).rows[0].s);
  console.log('baseline', gb(baseline), '| abort if growth >', gb(MAXG));
  await c.query(ddl);
  const dirs = fs.readdirSync(path.join(base, 'x_' + kind)).sort((a, b) => parseInt(a) - parseInt(b));
  const colList = cols.map((x) => x.name).concat(['roll_stage', 'source_file', 'match_key']).join(',');
  let total = 0;
  for (const d of dirs) {
    const co = parseInt(d); if (only && !only.includes(co)) continue;
    if ((await c.query(`select 1 from ${table} where co_no=$1 limit 1`, [co])).rowCount) { console.log('skip', d); continue; }
    const f = fs.readdirSync(path.join(base, 'x_' + kind, d)).find((x) => /\.csv$/i.test(x));
    const stage = /_(\d{4})([FP])$/.exec(d)[2]; let n = 0, badco = 0; const t0 = Date.now();
    const rows = fs.createReadStream(path.join(base, 'x_' + kind, d, f)).pipe(csv({ mapHeaders: ({ header }) => header.trim().replace(/^﻿/, '') }));
    const lines = Readable.from((async function* () {
      let buf = [];
      for await (const r of rows) {
        const vals = cols.map((x) => { const v = r[x.csv]; return q(v == null ? '' : v.trim()); });
        if (Number(r.CO_NO) !== co) badco++;
        vals.push(stage, q(f), q(strict(r.PARCEL_ID) || ''));
        buf.push(vals.join(',')); n++;
        if (buf.length >= 2000) { yield buf.join('\n') + '\n'; buf = []; }
      }
      if (buf.length) yield buf.join('\n') + '\n';
    })());
    await c.query('BEGIN');
    try {
      await pipeline(lines, c.query(copyFrom(`COPY ${table} (${colList}) FROM STDIN WITH (FORMAT csv)`)));
      const got = (await c.query(`select count(*)::int n from ${table} where co_no=$1`, [co])).rows[0].n;
      if (got !== n) throw new Error(`row mismatch co ${co}: parsed ${n} loaded ${got}`);
      if (badco) throw new Error(`co ${co}: ${badco} rows with CO_NO != filename`);
      await c.query('COMMIT');
    } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; }
    total += n;
    const size = Number((await c.query('select pg_database_size(current_database()) s')).rows[0].s);
    console.log(`ok ${d} stage=${stage} rows=${n} ${((Date.now() - t0) / 1000).toFixed(1)}s db=${gb(size)}`);
    if (size - baseline > MAXG) throw new Error('size guard tripped: db grew ' + gb(size - baseline));
  }
  await c.query("SET maintenance_work_mem = '1GB'"); console.log('indexing...');
  await c.query(idx); await c.query(`ANALYZE ${table}`);
  console.log('ALLDONE', kind, year, 'rows this run', total); await c.end();
})().catch((e) => { console.error('FATAL', e.message); process.exit(1); });
